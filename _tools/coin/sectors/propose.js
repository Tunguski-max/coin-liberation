// Sector selection proposal (ticket #4, ADR 0016).
// Usage from the repo root: node _tools/coin/sectors/propose.js
// Reads rules.json and the COIN mission.sqm, writes selection.json (input for writing the
// mission base) plus docs/sektorauswahl.md and docs/sektorauswahl.svg for review.
const fs = require('fs');
const path = require('path');
const { parseMarkers, selectSectors, diffSelections, renderList, renderSvg } = require('./sectors');

const repoRoot = path.resolve(__dirname, '..', '..', '..');
const rulesFile = path.join(__dirname, 'rules.json');
const selectionFile = path.join(__dirname, 'selection.json');
const listFile = path.join(repoRoot, 'docs', 'sektorauswahl.md');
const svgFile = path.join(repoRoot, 'docs', 'sektorauswahl.svg');

const rules = JSON.parse(fs.readFileSync(rulesFile, 'utf8'));
const markers = parseMarkers(fs.readFileSync(path.join(repoRoot, rules.missionSqm), 'utf8'));
const previous = fs.existsSync(selectionFile) ? JSON.parse(fs.readFileSync(selectionFile, 'utf8')) : null;

let result;
try {
    result = selectSectors(markers, rules);
} catch (error) {
    console.error(`[COIN] sectors: ERROR - ${error.message}`);
    process.exit(1);
}

const selection = {
    note: 'Generated by _tools/coin/sectors/propose.js from rules.json - do not edit by hand',
    selected: result.selected.map(({ name, text, role, x, y, added }) => ({ name, text, role, x, y, ...(added && { added }) })),
};

fs.writeFileSync(selectionFile, JSON.stringify(selection, null, 4) + '\n');
fs.writeFileSync(listFile, renderList(result, previous));
fs.writeFileSync(svgFile, renderSvg(result, rules) + '\n');

const count = role => result.selected.filter(s => s.role === role).length;
console.log(`[COIN] sectors: capital ${count('capital')}, towns ${count('downgradedCapital') + count('town')} ` +
    `(${count('downgradedCapital')} downgraded capitals), supply points ${count('supplyPoint')}, military posts ${count('militaryPost')}`);
if (previous) {
    const { added, dropped } = diffSelections(previous, selection.selected);
    console.log(`[COIN] sectors: new: ${added.join(', ') || '-'} | dropped: ${dropped.join(', ') || '-'}`);
}
for (const warning of result.warnings) console.log(`[COIN] sectors: WARNING - ${warning}`);
console.log(`[COIN] sectors: wrote ${path.relative(repoRoot, listFile)}, ${path.relative(repoRoot, svgFile)}, ${path.relative(repoRoot, selectionFile)}`);
